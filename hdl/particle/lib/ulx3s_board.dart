// =============================================================================
// File: hdl/particle/lib/ulx3s_board.dart
// Architecture: Particle 32-bit RISC on Lattice ECP5 (ULX3S)
// Description: SystemVerilog board wrapper for the ULX3S: the ECP5 PLL and
//              the mapping from the board's pin names (ulx3s_v20.lpf) to
//              ParticleSingleCoreTop.
// =============================================================================
//
// The wrapper is written as text because it needs two things ROHD 0.5 can't
// express: the vendor PLL primitive (EHXPLLL) and bidirectional header pins
// (gp[] and gn[] are inout, and only gp[0] and gp[1] are used).
//
// Pins (names from boards/ulx3s/ulx3s_v20.lpf):
//   clk_25mhz        25 MHz oscillator, into the PLL
//   btn[0]           power button (active low): reset
//   ftdi_txd (M1)    FTDI -> FPGA: FTDI UART receive
//   ftdi_rxd (L4)    FPGA -> FTDI: FTDI UART transmit
//   gp[0]  (B11)     GPIO UART transmit
//   gp[1]  (A10)     GPIO UART receive
//   led[7:0]         low byte of the fetch address (Parcore: its LEDs)
//   btn[6:1]         FIRE1, FIRE2, UP, DOWN, LEFT, RIGHT (Parcore only)
//   wifi_gpio0 (L2)  held high so the ESP32 doesn't reset or reprogram the FPGA

/// EHXPLLL settings for one output clock, with CLKOP as the feedback.
class Ecp5PllSettings {
  final int clkiDiv;
  final int clkfbDiv;
  final int clkopDiv;
  final int inputHz;
  final int outputHz;

  const Ecp5PllSettings(
      this.clkiDiv, this.clkfbDiv, this.clkopDiv, this.inputHz, this.outputHz);

  int get vcoHz => outputHz * clkopDiv;
  int get clkopCphase => (clkopDiv - 1) ~/ 2;

  /// Finds settings that give exactly [outputHz] from [inputHz], within the
  /// ECP5 limits: PFD (input / CLKI_DIV) 3.125–400 MHz, VCO 400–800 MHz.
  /// Throws if the frequency can't be made exactly.
  static Ecp5PllSettings find(int inputHz, int outputHz) {
    for (var clki = 1; clki <= 128; clki++) {
      if (inputHz % clki != 0) continue;
      final pfd = inputHz ~/ clki;
      if (pfd < 3125000 || pfd > 400000000) continue;
      if (outputHz % pfd != 0) continue;
      final fb = outputHz ~/ pfd;
      if (fb < 1 || fb > 80) continue;
      // The CLKOP divider whose VCO frequency is nearest 600 MHz, the middle
      // of the range
      int? best;
      for (var op = 1; op <= 128; op++) {
        final vco = outputHz * op;
        if (vco < 400000000 || vco > 800000000) continue;
        if (best == null ||
            (vco - 600000000).abs() < (outputHz * best - 600000000).abs()) {
          best = op;
        }
      }
      if (best != null) {
        return Ecp5PllSettings(clki, fb, best, inputHz, outputHz);
      }
    }
    throw ArgumentError(
        'The ECP5 PLL can\'t make exactly $outputHz Hz from $inputHz Hz');
  }
}

/// The board top level, `ulx3s_board`, which instantiates [coreModule].
/// With [buttons], the core module also has a `buttons` input, given
/// btn[6:1] (FIRE1, FIRE2, UP, DOWN, LEFT, RIGHT; 1 = pressed). With
/// [flash], it also has `flash_csn`, `flash_sck` and `flash_mosi` outputs
/// and a `flash_miso` input, wired to the board's SPI flash: its clock pin is
/// the ECP5's configuration clock, reached through the USRMCLK primitive
/// (the LPF must then have MASTER_SPI_PORT=DISABLE), and HOLD# and WP# are
/// held high.
String ulx3sBoardVerilog({
  required Ecp5PllSettings pll,
  String coreModule = 'particle_single_core_top',
  bool buttons = false,
  bool flash = false,
}) {
  final flashPorts = flash
      ? '\n  output logic        flash_csn,'
          '\n  output logic        flash_mosi,'
          '\n  input  logic        flash_miso,'
          '\n  output logic        flash_holdn,'
          '\n  output logic        flash_wpn,'
      : '';
  final flashPins = flash
      ? '\n    .flash_csn(flash_csn),'
          '\n    .flash_sck(flashSck),'
          '\n    .flash_mosi(flash_mosi),'
          '\n    .flash_miso(flash_miso),'
      : '';
  final flashClock = flash
      ? '\n  // The flash\'s clock is the configuration clock pin, driven '
          'through USRMCLK'
          '\n  USRMCLK flash_clock (.USRMCLKI(flashSck), .USRMCLKTS(1\'b0));'
          '\n  assign flash_holdn = 1\'b1;'
          '\n  assign flash_wpn = 1\'b1;\n'
      : '';
  String mhz(int hz) => (hz / 1e6).toString().replaceAll(RegExp(r'\.0$'), '');
  return '''
// =============================================================================
// ulx3s_board: ULX3S top level (generated by hdl/particle/bin/generate_ulx3s.dart)
// Clock: ${mhz(pll.inputHz)} MHz -> ${mhz(pll.outputHz)} MHz (VCO ${mhz(pll.vcoHz)} MHz)
// =============================================================================
module ulx3s_board (
  input  logic        clk_25mhz,
  input  logic [6:0]  btn,
  output logic [7:0]  led,
  input  logic        ftdi_txd,
  output logic        ftdi_rxd,
  inout  wire  [27:0] gp,$flashPorts
  output logic        wifi_gpio0
);
  logic clk;
  logic pllLocked;

  (* FREQUENCY_PIN_CLKI="${mhz(pll.inputHz)}" *)
  (* FREQUENCY_PIN_CLKOP="${mhz(pll.outputHz)}" *)
  (* ICP_CURRENT="12" *) (* LPF_RESISTOR="8" *) (* MFG_ENABLE_FILTEROPAMP="1" *) (* MFG_GMCREF_SEL="2" *)
  EHXPLLL #(
    .PLLRST_ENA("DISABLED"),
    .INTFB_WAKE("DISABLED"),
    .STDBY_ENABLE("DISABLED"),
    .DPHASE_SOURCE("DISABLED"),
    .OUTDIVIDER_MUXA("DIVA"),
    .OUTDIVIDER_MUXB("DIVB"),
    .OUTDIVIDER_MUXC("DIVC"),
    .OUTDIVIDER_MUXD("DIVD"),
    .CLKI_DIV(${pll.clkiDiv}),
    .CLKOP_ENABLE("ENABLED"),
    .CLKOP_DIV(${pll.clkopDiv}),
    .CLKOP_CPHASE(${pll.clkopCphase}),
    .CLKOP_FPHASE(0),
    .FEEDBK_PATH("CLKOP"),
    .CLKFB_DIV(${pll.clkfbDiv})
  ) pll (
    .RST(1'b0),
    .STDBY(1'b0),
    .CLKI(clk_25mhz),
    .CLKOP(clk),
    .CLKFB(clk),
    .CLKINTFB(),
    .PHASESEL0(1'b0),
    .PHASESEL1(1'b0),
    .PHASEDIR(1'b1),
    .PHASESTEP(1'b1),
    .PHASELOADREG(1'b1),
    .PLLWAKESYNC(1'b0),
    .ENCLKOP(1'b0),
    .LOCK(pllLocked)
  );

  logic gpioTx;${flash ? '\n  logic flashSck;' : ''}

  $coreModule core_top (
    .clk(clk),
    .reset_n(btn[0] & pllLocked),
    .ftdi_rx_pin(ftdi_txd),
    .gpio_rx_pin(gp[1]),
    .ftdi_tx_pin(ftdi_rxd),
    .gpio_tx_pin(gpioTx),${buttons ? '\n    .buttons(btn[6:1]),' : ''}$flashPins
    .leds(led)
  );
$flashClock
  assign gp[0] = gpioTx;
  assign gp[27:1] = 27'bz;
  assign wifi_gpio0 = 1'b1;
endmodule : ulx3s_board
''';
}
